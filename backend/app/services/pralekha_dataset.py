def get_common_aligned_matrix(
    required_languages: Optional[List[str]] = None
) -> List[Dict[str, Any]]:
    """
    Extracts strictly those items that have authentic translations in EVERY single
    required language (default: all 22 scheduled Indian languages + English = 23 languages).
    Guarantees 100% full n-way multi-lingual alignment across all languages.
    """
    langs = set(required_languages) if required_languages else set(ALL_LANGUAGES)
    common_items: List[Dict[str, Any]] = []

    for item in MULTILINGUAL_CORPUS_MATRIX:
        translations = item.get("translations", {})
        # Check that every single required language is present with non-empty text
        if all(l in translations and str(translations[l]).strip() for l in langs):
            common_items.append(item)

    logger.info(
        f"Retrieved {len(common_items)} sentences with full common alignment across all {len(langs)} languages."
    )
    return common_items


def get_common_aligned_sentences() -> Dict[str, Dict[str, str]]:
    """
    Returns a dictionary mapping sentence_id -> {lang_code: text} for all
    sentences that are common across all 23 languages.
    """
    matrix = get_common_aligned_matrix()
    return {item["id"]: item["translations"] for item in matrix}


