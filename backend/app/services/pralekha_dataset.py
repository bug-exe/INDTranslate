def train_val_test_split(
    pairs: List[ParallelSentencePair],
    val_ratio: float = 0.1,
    test_ratio: float = 0.05,
    seed: int = 42,
    shuffle: bool = True,
    stratify_by_domain: bool = True
) -> Tuple[List[ParallelSentencePair], List[ParallelSentencePair], List[ParallelSentencePair]]:
    """
    Splits parallel sentence pairs into train, val, and test partitions deterministically.
    """
    if not pairs:
        return [], [], []

    rng = random.Random(seed)

    if not stratify_by_domain:
        items = list(pairs)
        if shuffle:
            rng.shuffle(items)
        n = len(items)
        n_val = int(n * val_ratio)
        n_test = int(n * test_ratio)
        train_set = items[: n - n_val - n_test]
        val_set = items[n - n_val - n_test : n - n_test]
        test_set = items[n - n_test :]
        return train_set, val_set, test_set

    # Stratified split by domain to ensure balanced domain representations
    domain_buckets: Dict[str, List[ParallelSentencePair]] = {}
    for p in pairs:
        dom = getattr(p, "domain", None) or (p.get("domain") if isinstance(p, dict) else "general") or "general"
        domain_buckets.setdefault(dom, []).append(p)

    train_set, val_set, test_set = [], [], []

    for d, bucket in domain_buckets.items():
        if shuffle:
            rng.shuffle(bucket)
        n = len(bucket)
        n_val = max(1, int(n * val_ratio)) if val_ratio > 0 and n > 2 else 0
        n_test = max(1, int(n * test_ratio)) if test_ratio > 0 and n > 4 else 0

        train_part = bucket[: n - n_val - n_test]
        val_part = bucket[n - n_val - n_test : n - n_test]
        test_part = bucket[n - n_test :]

        train_set.extend(train_part)
        val_set.extend(val_part)
        test_set.extend(test_part)

    if shuffle:
        rng.shuffle(train_set)
        rng.shuffle(val_set)
        rng.shuffle(test_set)

    logger.info(
        f"Pralekha dataset split: Train={len(train_set)}, Val={len(val_set)}, Test={len(test_set)}"
    )
    return train_set, val_set, test_set


