def get_pralekha_dataloaders(
    pairs: Optional[List[ParallelSentencePair]] = None,
    tokenizer: Optional[PralekhaTokenizer] = None,
    batch_size: int = 16,
    val_ratio: float = 0.1,
    test_ratio: float = 0.05,
    max_source_length: int = 128,
    max_target_length: int = 128,
    shuffle: bool = True,
    seed: int = 42,
    num_workers: int = 0,
    pin_memory: bool = False,
    lang_pairs: Optional[List[Tuple[str, str]]] = None,
    domains: Optional[List[str]] = None,
    max_pairs: Optional[int] = None,
    require_common_among_all: bool = True,
    use_strict_db: bool = False,
    strict_db_path: Optional[Path] = None,
    balanced_132way: bool = False,
    use_spm: bool = False
) -> Tuple[DataLoader, DataLoader, Optional[DataLoader], PralekhaTokenizer]:
    """
    Constructs high-performance PyTorch DataLoaders ready for training Seq2Seq models.
    Supports either in-memory common aligned multi-domain pairs or streaming from
    the strict 12-way SQLite database (backend/data/pralekha_strict_12way.db).
    
    Returns:
        (train_loader, val_loader, test_loader, tokenizer)
    """
    if pairs is None:
        if use_strict_db:
            from backend.app.services.pralekha_strict_db import (
                load_pairs_from_strict_db,
                load_balanced_500k_pairs,
                PRALEKHA_STRICT_DB_PATH
            )
            target_db = strict_db_path or PRALEKHA_STRICT_DB_PATH
            if balanced_132way or (max_pairs and max_pairs >= 100000 and lang_pairs is None):
                logger.info(f"Loading balanced 132-way pairs from strict database: {target_db}")
                db_rows = load_balanced_500k_pairs(
                    db_path=target_db,
                    target_pairs=max_pairs or 500000,
                    seed=seed
                )
            else:
                logger.info(f"Loading training pairs from strict 12-way database: {target_db}")
                db_rows = load_pairs_from_strict_db(
                    db_path=target_db,
                    lang_pairs=lang_pairs,
                    max_pairs=max_pairs
                )
            pairs = [
                ParallelSentencePair(
                    source_text=r["source_text"],
                    target_text=r["target_text"],
                    source_lang=r["source_lang"],
                    target_lang=r["target_lang"],
                    domain=r.get("split", "strict_12way"),
                    id=f"{r.get('doc_id', 'doc')}_{r['source_lang']}_{r['target_lang']}"
                )
                for r in db_rows
            ]
            logger.info(f"Loaded {len(pairs)} direct pairs from strict 12-way DB.")
        else:
            pairs = get_pralekha_parallel_pairs(
                lang_pairs=lang_pairs,
                domains=domains,
                max_pairs=max_pairs,
                include_all_indic_pairs=True,
                require_common_among_all=require_common_among_all
            )
    elif pairs and len(pairs) > 0 and isinstance(pairs[0], dict):
        pairs = [
            ParallelSentencePair(
                source_text=r["source_text"],
                target_text=r["target_text"],
                source_lang=r["source_lang"],
                target_lang=r["target_lang"],
                domain=r.get("domain", r.get("split", "strict_12way")),
                id=str(r.get("id", f"{r.get('doc_id', 'doc')}_{r['source_lang']}_{r['target_lang']}"))
            )
            for r in pairs
        ]

    if tokenizer is None:
        if use_spm:
            tokenizer = PralekhaSentencePieceTokenizer()
        else:
            tokenizer = PralekhaTokenizer()

    train_pairs, val_pairs, test_pairs = train_val_test_split(
        pairs,
        val_ratio=val_ratio,
        test_ratio=test_ratio,
        seed=seed,
        shuffle=shuffle,
        stratify_by_domain=True
    )

    collator = PralekhaDataCollator(tokenizer=tokenizer)

    train_ds = PralekhaPyTorchDataset(train_pairs, tokenizer, max_source_length, max_target_length)
    val_ds = PralekhaPyTorchDataset(val_pairs, tokenizer, max_source_length, max_target_length)
    test_ds = PralekhaPyTorchDataset(test_pairs, tokenizer, max_source_length, max_target_length) if test_pairs else None

    train_loader = DataLoader(
        train_ds,
        batch_size=batch_size,
        shuffle=shuffle,
        collate_fn=collator,
        num_workers=num_workers,
        pin_memory=pin_memory
    )

    val_loader = DataLoader(
        val_ds,
        batch_size=batch_size,
        shuffle=False,
        collate_fn=collator,
        num_workers=num_workers,
        pin_memory=pin_memory
    )

    test_loader = (
        DataLoader(
            test_ds,
            batch_size=batch_size,
            shuffle=False,
            collate_fn=collator,
            num_workers=num_workers,
            pin_memory=pin_memory
        )
        if test_ds
        else None
    )

    logger.info(
        f"Initialized Pralekha DataLoaders: Train Batches={len(train_loader)}, "
        f"Val Batches={len(val_loader)}, Batch Size={batch_size}"
    )

    return train_loader, val_loader, test_loader, tokenizer


# ---------------------------------------------------------------------------
# Corpus Statistics Utility
# ---------------------------------------------------------------------------

def get_corpus_statistics(pairs: List[ParallelSentencePair]) -> Dict[str, Any]:
    """Generates comprehensive corpus metrics across languages and domains."""
    total_pairs = len(pairs)
    domain_counts: Dict[str, int] = {}
    lang_pair_counts: Dict[str, int] = {}
    src_langs: Set[str] = set()
    tgt_langs: Set[str] = set()
    total_src_tokens = 0
    total_tgt_tokens = 0

    for p in pairs:
        domain_counts[p.domain] = domain_counts.get(p.domain, 0) + 1
        pair_key = f"{p.source_lang}->{p.target_lang}"
        lang_pair_counts[pair_key] = lang_pair_counts.get(pair_key, 0) + 1
        src_langs.add(p.source_lang)
        tgt_langs.add(p.target_lang)
        total_src_tokens += len(p.source_text.split())
        total_tgt_tokens += len(p.target_text.split())

    return {
        "total_pairs": total_pairs,
        "unique_source_languages": sorted(list(src_langs)),
        "unique_target_languages": sorted(list(tgt_langs)),
        "language_count": len(src_langs.union(tgt_langs)),
        "domain_distribution": domain_counts,
        "total_language_pairs": len(lang_pair_counts),
        "avg_source_words": round(total_src_tokens / total_pairs, 2) if total_pairs else 0.0,
        "avg_target_words": round(total_tgt_tokens / total_pairs, 2) if total_pairs else 0.0
    }


