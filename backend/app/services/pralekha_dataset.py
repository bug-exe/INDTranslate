# Tokenizer Utilities: PralekhaTokenizer
# ---------------------------------------------------------------------------

class PralekhaTokenizer:
    """
    Multilingual Indic Seq2Seq Tokenizer for AI4Bharat Pralekha models.
    Supports target language prefix tokens (<2hi>, <2bn>, <2ta>, etc.), special tokens,
    and extensive multilingual subword / character-level vocabulary covering all 22
    scheduled scripts + Latin English.
    """

    PAD_TOKEN = "<pad>"
    UNK_TOKEN = "<unk>"
    BOS_TOKEN = "<bos>"
    EOS_TOKEN = "<eos>"
    MASK_TOKEN = "<mask>"

    SPECIAL_TOKENS = [PAD_TOKEN, UNK_TOKEN, BOS_TOKEN, EOS_TOKEN, MASK_TOKEN]

    def __init__(
        self,
        vocab: Optional[Dict[str, int]] = None,
        spm_model_path: Optional[Union[str, Path]] = None
    ):
        self.spm_model_path: Optional[Path] = Path(spm_model_path) if spm_model_path else None
        self.sp: Any = None

        if self.spm_model_path and self.spm_model_path.exists():
            try:
                import sentencepiece as spm
                self.sp = spm.SentencePieceProcessor()
                self.sp.load(str(self.spm_model_path))
                self.token2id: Dict[str, int] = {
                    self.sp.id_to_piece(i): i for i in range(self.sp.get_piece_size())
                }
            except Exception as e:
                logger.warning(f"Failed to load SentencePiece model from {self.spm_model_path}: {e}")
                self.sp = None

        if self.sp is None:
            if vocab is not None:
                self.token2id = dict(vocab)
            else:
                self.token2id = self._build_default_vocabulary()

        self.id2token: Dict[int, str] = {idx: tok for tok, idx in self.token2id.items()}

        self.pad_token_id: int = self.token2id.get(self.PAD_TOKEN, 0)
        self.unk_token_id: int = self.token2id.get(self.UNK_TOKEN, 1)
        self.bos_token_id: int = self.token2id.get(self.BOS_TOKEN, 2)
        self.eos_token_id: int = self.token2id.get(self.EOS_TOKEN, 3)
        self.mask_token_id: int = self.token2id.get(self.MASK_TOKEN, 4)

    @property
    def vocab_size(self) -> int:
        return len(self.token2id)

    def get_vocab(self) -> Dict[str, int]:
        return dict(self.token2id)

    @classmethod
    def get_lang_token(cls, lang_code: str) -> str:
        """Returns target language routing token, e.g. '<2hi>' or '<2ta>'."""
        code = lang_code.lower().strip()
        return f"<2{code}>"

    def _build_default_vocabulary(self) -> Dict[str, int]:
        """Constructs rich initial multilingual vocabulary covering all 23 languages."""
        v: Dict[str, int] = {}
        idx = 0

        # 1. Base special tokens
        for st in self.SPECIAL_TOKENS:
            v[st] = idx
            idx += 1

        # 2. Language routing tokens for all 23 languages (<2as>, <2bn>, ..., <2en>)
        for lang in sorted(ALL_LANGUAGES):
            lang_tok = self.get_lang_token(lang)
            v[lang_tok] = idx
            idx += 1

        # 3. Harvest characters and frequent tokens from MULTILINGUAL_CORPUS_MATRIX
        seen_chars: Set[str] = set()
        seen_words: Set[str] = set()

        for item in MULTILINGUAL_CORPUS_MATRIX:
            for text in item["translations"].values():
                for char in text:
                    if not char.isspace():
                        seen_chars.add(char)
                words = re.findall(r"\w+|[^\w\s]", text, re.UNICODE)
                for w in words:
                    seen_words.add(w)

        # Add characters first for subword fallback
        for char in sorted(list(seen_chars)):
            if char not in v:
                v[char] = idx
                idx += 1

        # Add common words/tokens
        for w in sorted(list(seen_words)):
            if w not in v:
                v[w] = idx
                idx += 1

        # Add basic ASCII alphanumeric and punctuation
        for ascii_char in "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789.,!?:;\"'()[]{}/-_+=@#$%^&*~":
            if ascii_char not in v:
                v[ascii_char] = idx
                idx += 1

        return v

    def tokenize(self, text: str) -> List[str]:
        """Splits text into known subwords, words, or character tokens."""
        if not text:
            return []
        if self.sp is not None:
            return self.sp.encode(text.strip(), out_type=str)
        tokens: List[str] = []
        raw_words = re.findall(r"\w+|[^\w\s]", text.strip(), re.UNICODE)
        for word in raw_words:
            if word in self.token2id:
                tokens.append(word)
            else:
                # Character fallback
                for char in word:
                    if char in self.token2id:
                        tokens.append(char)
                    else:
                        tokens.append(self.UNK_TOKEN)
        return tokens

    def encode(
        self,
        text: str,
        target_lang: Optional[str] = None,
        max_length: int = 128,
        truncation: bool = True,
        add_special_tokens: bool = True
    ) -> List[int]:
        """
        Encodes string into token IDs.
        If target_lang is specified, prepends language direction token (e.g. <2hi>).
        """
        if self.sp is not None:
            clean_text = str(text).strip()
            ids = self.sp.encode(clean_text, out_type=int)
            if add_special_tokens:
                prefix: List[int] = []
                if target_lang:
                    lang_tok = self.get_lang_token(target_lang)
                    prefix.append(self.token2id.get(lang_tok, self.unk_token_id))
                else:
                    prefix.append(self.bos_token_id)
                ids = prefix + ids + [self.eos_token_id]
            if truncation and len(ids) > max_length:
                ids = ids[:max_length - 1] + [self.eos_token_id]
            return ids

        token_strs = self.tokenize(text)
        ids = [self.token2id.get(tok, self.unk_token_id) for tok in token_strs]

        if add_special_tokens:
            prefix: List[int] = []
            if target_lang:
                lang_tok = self.get_lang_token(target_lang)
                prefix.append(self.token2id.get(lang_tok, self.unk_token_id))
            else:
                prefix.append(self.bos_token_id)

            ids = prefix + ids + [self.eos_token_id]

        if truncation and len(ids) > max_length:
            ids = ids[:max_length - 1] + [self.eos_token_id]

        return ids

    def decode(self, token_ids: List[int], skip_special_tokens: bool = True) -> str:
        """Decodes token IDs into a readable string."""
        if self.sp is not None:
            filtered_ids: List[int] = []
            special_ids = {self.pad_token_id, self.unk_token_id, self.bos_token_id, self.eos_token_id, self.mask_token_id}
            for tid in token_ids:
                if skip_special_tokens:
                    if tid in special_ids:
                        continue
                    piece = self.id2token.get(tid, "")
                    if piece.startswith("<2") and piece.endswith(">"):
                        continue
                filtered_ids.append(tid)
            text = self.sp.decode(filtered_ids)
            return text.strip()

        tokens: List[str] = []
        for tid in token_ids:
            tok = self.id2token.get(tid, self.UNK_TOKEN)
            if skip_special_tokens:
                if tok in self.SPECIAL_TOKENS or tok.startswith("<2"):
                    continue
            tokens.append(tok)

        text = "".join(tokens)
        # Clean up spacing around punctuation if Latin/general
        text = re.sub(r"\s+([.,!?:;])", r"\1", text)
        return text.strip()

    def get_script_mask(self, target_lang: str, device: Optional[torch.device] = None) -> torch.Tensor:
        """
        Computes a target-script logit mask tensor (shape: [vocab_size]).
        Allowed tokens for target_lang's script and universal punctuation have 0.0,
        while all other script tokens have -float('inf').
        """
        lang_clean = str(target_lang).lower().strip()
        if hasattr(self, "_script_masks") and lang_clean in self._script_masks:
            mask = self._script_masks[lang_clean]
            return mask.to(device) if device is not None else mask

        if not hasattr(self, "_script_masks"):
            self._script_masks = {}

        import unicodedata
        SCRIPT_BY_LANG: Dict[str, str] = {
            "hi": "DEVANAGARI", "mr": "DEVANAGARI", "sa": "DEVANAGARI", "ne": "DEVANAGARI",
            "kok": "DEVANAGARI", "mai": "DEVANAGARI", "doi": "DEVANAGARI", "brx": "DEVANAGARI",
            "bn": "BENGALI", "as": "BENGALI", "mni": "BENGALI",
            "pa": "GURMUKHI",
            "gu": "GUJARATI",
            "or": "ORIYA",
            "ta": "TAMIL",
            "te": "TELUGU",
            "kn": "KANNADA",
            "ml": "MALAYALAM",
            "ur": "ARABIC", "ks": "ARABIC", "sd": "ARABIC",
            "sat": "OL",
            "en": "LATIN"
        }
        target_script = SCRIPT_BY_LANG.get(lang_clean, "LATIN")
        mask = torch.full((self.vocab_size,), -float("inf"), dtype=torch.float32)

        # Always allow special tokens
        mask[self.pad_token_id] = 0.0
        mask[self.bos_token_id] = 0.0
        mask[self.eos_token_id] = 0.0

        for tok, tid in self.token2id.items():
            if tid < 28:
                continue
            if tok.startswith("<0x") and tok.endswith(">"):
                continue
            # Universal punctuation, digits, whitespace, SPM prefix
            clean_tok = tok.lstrip(" ").lstrip("▁")
            if clean_tok and all(c in '0123456789 .,?!:;-\'\"()/%\n\t\u200c\u200d' for c in clean_tok):
                mask[tid] = 0.0
                continue
            # Check script membership
            for c in clean_tok:
                name = unicodedata.name(c, "")
                if name and name.split()[0] == target_script:
                    mask[tid] = 0.0
                    break

        self._script_masks[lang_clean] = mask
        return mask.to(device) if device is not None else mask

    def get_combining_marks_mask(self, device: Optional[torch.device] = None) -> torch.Tensor:
        """Mask that suppresses orphaned combining marks at step 0."""
        if hasattr(self, "_combining_mask"):
            return self._combining_mask.to(device) if device is not None else self._combining_mask

        import unicodedata
        mask = torch.zeros((self.vocab_size,), dtype=torch.float32)
        for tok, tid in self.token2id.items():
            clean_tok = tok.lstrip(" ").lstrip("▁")
            if len(clean_tok) == 1 and unicodedata.category(clean_tok) == "Mn":
                mask[tid] = -float("inf")
        self._combining_mask = mask
        return mask.to(device) if device is not None else mask

    def batch_encode(
        self,
        texts: List[str],
        target_langs: Optional[List[str]] = None,
        max_length: int = 128,
        padding: bool = True,
        truncation: bool = True
    ) -> Dict[str, torch.Tensor]:
        """Encodes a batch of texts into padded PyTorch tensors."""
        batch_ids = []
        for i, text in enumerate(texts):
            tl = target_langs[i] if target_langs and i < len(target_langs) else None
            ids = self.encode(text, target_lang=tl, max_length=max_length, truncation=truncation)
            batch_ids.append(ids)

        max_len = max(len(ids) for ids in batch_ids) if padding else max_length
        padded_ids = []
        attention_masks = []

        for ids in batch_ids:
            pad_len = max_len - len(ids)
            padded = ids + [self.pad_token_id] * pad_len
            mask = [1] * len(ids) + [0] * pad_len
            padded_ids.append(padded)
            attention_masks.append(mask)

        return {
            "input_ids": torch.tensor(padded_ids, dtype=torch.long),
            "attention_mask": torch.tensor(attention_masks, dtype=torch.long)
        }

    def save_pretrained(self, save_directory: Union[str, Path]) -> Path:
        """Saves tokenizer vocabulary and configuration to directory."""
        dir_path = Path(save_directory)
        dir_path.mkdir(parents=True, exist_ok=True)

        if self.sp is not None and self.spm_model_path and self.spm_model_path.exists():
            import shutil
            target_spm = dir_path / "sentencepiece.bpe.model"
            if self.spm_model_path.resolve() != target_spm.resolve():
                shutil.copy2(self.spm_model_path, target_spm)
            spm_vocab_path = dir_path / "spm_vocab.json"
            with open(spm_vocab_path, "w", encoding="utf-8") as f:
                json.dump(self.token2id, f, ensure_ascii=False, indent=2)

        vocab_path = dir_path / "pralekha_vocab.json"
        with open(vocab_path, "w", encoding="utf-8") as f:
            json.dump(self.token2id, f, ensure_ascii=False, indent=2)

        config_path = dir_path / "tokenizer_config.json"
        config = {
            "model_type": "sentencepiece_bpe" if self.sp is not None else "pralekha_tokenizer",
            "vocab_size": self.vocab_size,
            "pad_token": self.PAD_TOKEN,
            "unk_token": self.UNK_TOKEN,
            "bos_token": self.BOS_TOKEN,
            "eos_token": self.EOS_TOKEN,
            "mask_token": self.MASK_TOKEN,
            "pad_token_id": self.pad_token_id,
            "unk_token_id": self.unk_token_id,
            "bos_token_id": self.bos_token_id,
            "eos_token_id": self.eos_token_id,
            "supported_languages": ALL_LANGUAGES,
            "spm_model_file": "sentencepiece.bpe.model" if self.sp is not None else None
        }
        with open(config_path, "w", encoding="utf-8") as f:
            json.dump(config, f, indent=2)

        logger.info(f"Saved PralekhaTokenizer ({self.vocab_size} tokens) to {dir_path}")
        return dir_path

    @classmethod
    def from_pretrained(cls, save_directory: Union[str, Path], use_spm: Optional[bool] = None) -> PralekhaTokenizer:
        """Loads tokenizer from saved directory or fallback default."""
        dir_path = Path(save_directory)
        spm_path = dir_path / "sentencepiece.bpe.model"
        if not spm_path.exists():
            spm_path = dir_path / "sentencepiece.model"

        if (use_spm is True or (use_spm is None and not (dir_path / "pralekha_vocab.json").exists() and not (dir_path / "vocab.json").exists())) and spm_path.exists():
            return cls(spm_model_path=spm_path)

        vocab_path = dir_path / "pralekha_vocab.json"
        if not vocab_path.exists():
            vocab_path = dir_path / "vocab.json"
        if not vocab_path.exists():
            vocab_path = dir_path / "spm_vocab.json"

        if vocab_path.exists():
            with open(vocab_path, "r", encoding="utf-8") as f:
                vocab = json.load(f)
            return cls(vocab=vocab)

        if spm_path.exists():
            return cls(spm_model_path=spm_path)

        return cls()


