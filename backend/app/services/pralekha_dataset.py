def get_pralekha_parallel_pairs(
    lang_pairs: Optional[List[Tuple[str, str]]] = None,
    domains: Optional[List[str]] = None,
    max_pairs: Optional[int] = None,
    include_all_indic_pairs: bool = True,
    require_common_among_all: bool = True
) -> List[ParallelSentencePair]:
    """
    Extracts high-quality parallel sentence pairs from the aligned multilingual matrix.
    
    Args:
        lang_pairs: Optional list of (source_lang, target_lang) tuples. If None,
                    generates all valid permutations across the 23 supported languages.
        domains: Optional filter for domains (e.g. ['governance', 'healthcare']).
        max_pairs: Optional upper bound on generated pairs (useful for quick unit tests).
        include_all_indic_pairs: When True, produces direct Indic-to-Indic pairs
                                 without pivoting through English.
        require_common_among_all: When True (default), strictly uses data that is
                                 common and aligned across ALL 22 scheduled languages + English.
    """
    pairs: List[ParallelSentencePair] = []
    selected_domains = set(domains) if domains else None
    allowed_pairs = set(lang_pairs) if lang_pairs else None

    # Filter base matrix to strictly common-aligned sentences if required
    base_matrix = get_common_aligned_matrix() if require_common_among_all else MULTILINGUAL_CORPUS_MATRIX

    for item in base_matrix:
        item_id = item["id"]
        domain = item["domain"]
        if selected_domains and domain not in selected_domains:
            continue

        translations = item["translations"]
        langs_present = [l for l in ALL_LANGUAGES if l in translations and translations[l].strip()]

        for src_lang in langs_present:
            src_text = translations[src_lang].strip()
            for tgt_lang in langs_present:
                if src_lang == tgt_lang:
                    continue  # skip identity

                # Filter by allowed_pairs if user restricted
                if allowed_pairs and (src_lang, tgt_lang) not in allowed_pairs:
                    continue

                if not include_all_indic_pairs and src_lang != "en" and tgt_lang != "en":
                    continue

                pair_id = f"{item_id}_{src_lang}_{tgt_lang}"
                pair = ParallelSentencePair(
                    source_text=src_text,
                    target_text=translations[tgt_lang].strip(),
                    source_lang=src_lang,
                    target_lang=tgt_lang,
                    domain=domain,
                    id=pair_id
                )
                pairs.append(pair)
                if max_pairs and len(pairs) >= max_pairs:
                    return pairs

    return pairs


def get_common_aligned_parallel_pairs(
    lang_pairs: Optional[List[Tuple[str, str]]] = None,
    domains: Optional[List[str]] = None,
    max_pairs: Optional[int] = None
) -> List[ParallelSentencePair]:
    """
    Convenience helper to extract parallel sentence pairs drawn EXCLUSIVELY
    from sentences that are common across all 22 scheduled languages + English.
    """
    return get_pralekha_parallel_pairs(
        lang_pairs=lang_pairs,
        domains=domains,
        max_pairs=max_pairs,
        include_all_indic_pairs=True,
        require_common_among_all=True
    )


def load_pralekha_from_file(file_path: Union[str, Path]) -> List[ParallelSentencePair]:
    """Loads parallel sentence pairs from JSON, JSONL, CSV, or TSV."""
    path = Path(file_path)
    if not path.exists():
        raise FileNotFoundError(f"Dataset file not found: {path}")

    pairs: List[ParallelSentencePair] = []
    suffix = path.suffix.lower()

    if suffix == ".json":
        with open(path, "r", encoding="utf-8") as f:
            data = json.load(f)
            if isinstance(data, list):
                for row in data:
                    pairs.append(ParallelSentencePair.from_dict(row))
            elif isinstance(data, dict) and "data" in data:
                for row in data["data"]:
                    pairs.append(ParallelSentencePair.from_dict(row))
    elif suffix == ".jsonl":
        with open(path, "r", encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if line:
                    pairs.append(ParallelSentencePair.from_dict(json.loads(line)))
    elif suffix in (".csv", ".tsv"):
        delimiter = "\t" if suffix == ".tsv" else ","
        with open(path, "r", encoding="utf-8") as f:
            reader = csv.DictReader(f, delimiter=delimiter)
            for row in reader:
                pairs.append(ParallelSentencePair.from_dict(row))
    else:
        raise ValueError(f"Unsupported dataset file extension: {suffix}")

    logger.info(f"Loaded {len(pairs)} parallel pairs from {path}")
    return pairs


def save_pralekha_dataset(
    pairs: List[ParallelSentencePair],
    output_path: Union[str, Path],
    format: str = "json"
) -> Path:
    """Saves parallel sentence pairs to disk in JSON, JSONL, or CSV format."""
    out_file = Path(output_path)
    out_file.parent.mkdir(parents=True, exist_ok=True)

    if format.lower() == "json":
        with open(out_file, "w", encoding="utf-8") as f:
            json.dump([p.to_dict() for p in pairs], f, ensure_ascii=False, indent=2)
    elif format.lower() == "jsonl":
        with open(out_file, "w", encoding="utf-8") as f:
            for p in pairs:
                f.write(json.dumps(p.to_dict(), ensure_ascii=False) + "\n")
    elif format.lower() == "csv":
        with open(out_file, "w", encoding="utf-8", newline="") as f:
            writer = csv.writer(f)
            writer.writerow(["id", "source_lang", "target_lang", "domain", "source_text", "target_text"])
            for p in pairs:
                writer.writerow([p.id or "", p.source_lang, p.target_lang, p.domain, p.source_text, p.target_text])
    else:
        raise ValueError(f"Unsupported output format: {format}")

    logger.info(f"Saved {len(pairs)} parallel pairs to {out_file}")
    return out_file


