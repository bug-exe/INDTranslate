# ---------------------------------------------------------------------------
# Data Structure: ParallelSentencePair
# ---------------------------------------------------------------------------

@dataclass
class ParallelSentencePair:
    """Represents a clean parallel sentence pair between any two languages."""
    source_text: str
    target_text: str
    source_lang: str
    target_lang: str
    domain: str = "general"
    id: Optional[str] = None

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> ParallelSentencePair:
        return cls(
            source_text=str(data.get("source_text", "")).strip(),
            target_text=str(data.get("target_text", "")).strip(),
            source_lang=str(data.get("source_lang", "")).strip().lower(),
            target_lang=str(data.get("target_lang", "")).strip().lower(),
            domain=str(data.get("domain", "general")),
            id=data.get("id")
        )


