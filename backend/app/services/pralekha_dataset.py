def load_ai4bharat_pralekha_dataset(
    data_dir: Optional[Union[str, Path]] = None,
    subset: str = "train",
    language_pairs: Optional[List[Tuple[str, str]]] = None,
    max_samples: Optional[int] = None
) -> List[ParallelSentencePair]:
    """
    Loads parallel data from the official AI4Bharat Pralekha dataset format
    (https://huggingface.co/datasets/ai4bharat/Pralekha).
    
    Parses files in data_dir (or backend/data/pralekha/).
    Supports both document-level alignments ('alignable') and sentence/document translation pairs ('train'/'dev'/'test').
    If local Pralekha files are not found, falls back gracefully to the built-in
    high-quality common aligned multi-domain corpus.
    """
    target_dir = Path(data_dir) if data_dir else PRALEKHA_DATA_DIR
    pairs: List[ParallelSentencePair] = []

    if target_dir.exists():
        candidate_files = (
            list(target_dir.glob("**/*.json"))
            + list(target_dir.glob("**/*.jsonl"))
            + list(target_dir.glob("**/*.tsv"))
            + list(target_dir.glob("**/*.csv"))
        )
        for fpath in candidate_files:
            try:
                loaded = load_pralekha_from_file(fpath)
                for p in loaded:
                    src = PRALEKHA_ISO_MAP.get(p.source_lang, p.source_lang)
                    tgt = PRALEKHA_ISO_MAP.get(p.target_lang, p.target_lang)
                    if language_pairs and (src, tgt) not in language_pairs:
                        continue
                    pairs.append(
                        ParallelSentencePair(
                            source_text=p.source_text,
                            target_text=p.target_text,
                            source_lang=src,
                            target_lang=tgt,
                            domain=p.domain or "ai4bharat_pralekha",
                            id=p.id,
                        )
                    )
                    if max_samples and len(pairs) >= max_samples:
                        return pairs
            except Exception as e:
                logger.warning(f"Could not parse file {fpath}: {e}")

    if pairs:
        logger.info(f"Loaded {len(pairs)} pairs from AI4Bharat Pralekha at {target_dir}")
        return pairs

    # Fallback to high-quality common aligned corpus
    logger.info(
        f"No local AI4Bharat Pralekha files found at {target_dir}. "
        "Using built-in common aligned multi-domain dataset covering all 22 scheduled languages + English."
    )
    return get_common_aligned_parallel_pairs(lang_pairs=language_pairs, max_pairs=max_samples)


