# Dynamic Batching Data Collator: PralekhaDataCollator
# ---------------------------------------------------------------------------

class PralekhaDataCollator:
    """
    Dynamic padding collator for PyTorch DataLoader.
    Pads input_ids and decoder_input_ids with pad_token_id.
    Pads labels with -100 (PyTorch CrossEntropyLoss default ignore_index).
    """

    def __init__(self, tokenizer: PralekhaTokenizer, label_pad_token_id: int = -100):
        self.tokenizer = tokenizer
        self.pad_token_id = tokenizer.pad_token_id
        self.label_pad_token_id = label_pad_token_id

    def __call__(self, batch: List[Dict[str, Any]]) -> Dict[str, Any]:
        max_src_len = max(item["input_ids"].size(0) for item in batch)
        max_tgt_len = max(item["labels"].size(0) for item in batch)
        max_dec_len = max(item["decoder_input_ids"].size(0) for item in batch)

        batch_input_ids = []
        batch_attention_mask = []
        batch_labels = []
        batch_decoder_input_ids = []

        batch_src_text = []
        batch_tgt_text = []
        batch_src_lang = []
        batch_tgt_lang = []
        batch_domain = []

        for item in batch:
            # Pad input_ids
            src_len = item["input_ids"].size(0)
            pad_src = max_src_len - src_len
            padded_input = torch.cat([item["input_ids"], torch.full((pad_src,), self.pad_token_id, dtype=torch.long)])
            mask = torch.cat([item["attention_mask"], torch.zeros((pad_src,), dtype=torch.long)])

            # Pad labels with -100
            tgt_len = item["labels"].size(0)
            pad_tgt = max_tgt_len - tgt_len
            padded_labels = torch.cat([item["labels"], torch.full((pad_tgt,), self.label_pad_token_id, dtype=torch.long)])

            # Pad decoder_input_ids
            dec_len = item["decoder_input_ids"].size(0)
            pad_dec = max_dec_len - dec_len
            padded_dec = torch.cat([item["decoder_input_ids"], torch.full((pad_dec,), self.pad_token_id, dtype=torch.long)])

            batch_input_ids.append(padded_input)
            batch_attention_mask.append(mask)
            batch_labels.append(padded_labels)
            batch_decoder_input_ids.append(padded_dec)

            batch_src_text.append(item["source_text"])
            batch_tgt_text.append(item["target_text"])
            batch_src_lang.append(item["source_lang"])
            batch_tgt_lang.append(item["target_lang"])
            batch_domain.append(item["domain"])

        return {
            "input_ids": torch.stack(batch_input_ids),
            "attention_mask": torch.stack(batch_attention_mask),
            "labels": torch.stack(batch_labels),
            "decoder_input_ids": torch.stack(batch_decoder_input_ids),
            "source_texts": batch_src_text,
            "target_texts": batch_tgt_text,
            "source_langs": batch_src_lang,
            "target_langs": batch_tgt_lang,
            "domains": batch_domain
        }


