class PralekhaPyTorchDataset(Dataset):
    """
    PyTorch Dataset wrapper for Pralekha parallel sentence pairs.
    Yields tokenized source tensors, target tensors, decoder inputs, and metadata.
    """

    def __init__(
        self,
        pairs: List[ParallelSentencePair],
        tokenizer: PralekhaTokenizer,
        max_source_length: int = 128,
        max_target_length: int = 128
    ):
        self.pairs = pairs
        self.tokenizer = tokenizer
        self.max_source_length = max_source_length
        self.max_target_length = max_target_length

    def __len__(self) -> int:
        return len(self.pairs)

    def __getitem__(self, idx: int) -> Dict[str, Any]:
        pair = self.pairs[idx]

        # Source encoding: prepends target language routing token (standard in IndicTrans2)
        # e.g., "<2hi> Hello, how are you? <eos>"
        src_ids = self.tokenizer.encode(
            pair.source_text,
            target_lang=pair.target_lang,
            max_length=self.max_source_length,
            truncation=True,
            add_special_tokens=True
        )

        # Target encoding: "<bos> नमस्ते, आप कैसे हैं? <eos>"
        tgt_ids = self.tokenizer.encode(
            pair.target_text,
            target_lang=None,
            max_length=self.max_target_length,
            truncation=True,
            add_special_tokens=True
        )

        # Decoder inputs: "<bos> नमस्ते, आप कैसे हैं?"
        # Labels: "नमस्ते, आप कैसे हैं? <eos>"
        decoder_input_ids = tgt_ids[:-1] if len(tgt_ids) > 1 else tgt_ids
        labels = tgt_ids[1:] if len(tgt_ids) > 1 else tgt_ids

        return {
            "input_ids": torch.tensor(src_ids, dtype=torch.long),
            "attention_mask": torch.tensor([1] * len(src_ids), dtype=torch.long),
            "labels": torch.tensor(labels, dtype=torch.long),
            "decoder_input_ids": torch.tensor(decoder_input_ids, dtype=torch.long),
            "source_text": pair.source_text,
            "target_text": pair.target_text,
            "source_lang": pair.source_lang,
            "target_lang": pair.target_lang,
            "domain": pair.domain
        }


