def get_all_languages() -> List[Dict[str, Any]]:
    """Returns list of all scheduled languages sorted by name."""
    return sorted(list(SCHEDULED_LANGUAGES.values()), key=lambda x: x["name"])

def get_language(code: str) -> Optional[Dict[str, Any]]:
    """Get metadata for a specific language code."""
    code = code.lower().strip()
    # Normalize aliases if any
    alias_map = {
        "asm": "as", "ben": "bn", "guj": "gu", "hin": "hi",
        "kan": "kn", "mal": "ml", "mar": "mr", "nep": "ne",
        "ori": "or", "pan": "pa", "san": "sa", "tam": "ta",
        "tel": "te", "urd": "ur", "snd": "sd", "meitei": "mni",
        "manipuri": "mni", "bengali": "bn", "hindi": "hi", "english": "en"
    }
    target = alias_map.get(code, code)
    return SCHEDULED_LANGUAGES.get(target)

def is_valid_language(code: str) -> bool:
    return get_language(code) is not None
