# Global in-memory cache of aligned documents
_ALIGNED_DOCUMENT_CORPUS: Optional[List[AlignedDocument]] = None


def get_aligned_documents() -> List[AlignedDocument]:
    """Returns the comprehensive aligned document corpus."""
    global _ALIGNED_DOCUMENT_CORPUS
    if _ALIGNED_DOCUMENT_CORPUS is None:
        _ALIGNED_DOCUMENT_CORPUS = _build_aligned_document_corpus()
    return _ALIGNED_DOCUMENT_CORPUS


def get_aligned_document_by_id(doc_id: str) -> Optional[AlignedDocument]:
    """Finds an aligned document by its unique identifier."""
    for doc in get_aligned_documents():
        if doc.doc_id == doc_id:
            return doc
    return None


def export_aligned_dataset_to_disk(output_dir: Optional[Path] = None) -> Dict[str, Any]:
    """
    Exports the N-way aligned document dataset to disk in multiple formats:
    1. json/all_aligned_documents.json: Full structural document hierarchy
    2. jsonl/aligned_documents.jsonl: Line-delimited JSON for data streaming
    3. by_language/<lang>/<doc_id>.txt: Pure full text of each document in each language
    4. parallel_document_pairs/<src>_<tgt>/<doc_id>.txt: Paragraph-aligned side-by-side or dual files
    5. metadata.json: Global alignment verification and language coverage statistics
    """
    out_path = Path(output_dir or DOCUMENTS_DATA_DIR)
    out_path.mkdir(parents=True, exist_ok=True)

    json_dir = out_path / "json"
    jsonl_dir = out_path / "jsonl"
    by_lang_dir = out_path / "by_language"
    pairs_dir = out_path / "parallel_document_pairs"

    for d in (json_dir, jsonl_dir, by_lang_dir, pairs_dir):
        d.mkdir(parents=True, exist_ok=True)

    docs = get_aligned_documents()
    docs_dict = [doc.to_dict() for doc in docs]

    # 1. Full JSON
    with open(json_dir / "all_aligned_documents.json", "w", encoding="utf-8") as f:
        json.dump(docs_dict, f, indent=2, ensure_ascii=False)

    # 2. JSONL
    with open(jsonl_dir / "aligned_documents.jsonl", "w", encoding="utf-8") as f:
        for d in docs_dict:
            f.write(json.dumps(d, ensure_ascii=False) + "\n")

    # 3. By Language Text Files
    total_files_written = 0
    for lang in ALL_23_LANGUAGES:
        lang_sub = by_lang_dir / lang
        lang_sub.mkdir(parents=True, exist_ok=True)
        for doc in docs:
            doc_file = lang_sub / f"{doc.doc_id}.txt"
            with open(doc_file, "w", encoding="utf-8") as f:
                f.write(doc.get_full_text(lang))
            total_files_written += 1

    # 4. Canonical Parallel Document Pairs (e.g. en_hi, hi_ta, bn_en, etc.)
    sample_pairs = [("en", "hi"), ("hi", "ta"), ("en", "bn"), ("hi", "mr"), ("en", "te")]
    for src_l, tgt_l in sample_pairs:
        pair_sub = pairs_dir / f"{src_l}_{tgt_l}"
        pair_sub.mkdir(parents=True, exist_ok=True)
        for doc in docs:
            pair_file = pair_sub / f"{doc.doc_id}_parallel.txt"
            with open(pair_file, "w", encoding="utf-8") as f:
                f.write(f"=== {doc.title.get(src_l, '')} | {doc.title.get(tgt_l, '')} ===\n\n")
                for p in doc.paragraphs:
                    for s in p.sentences:
                        f.write(f"[{src_l.upper()}] {s.get_text(src_l)}\n")
                        f.write(f"[{tgt_l.upper()}] {s.get_text(tgt_l)}\n\n")

    # 5. Dedicated Pralekha Official 12-Language Subset Export
    # Covers the 12 languages matching the official ai4bharat/Pralekha benchmark
