@dataclass
class AlignedSentence:
    """A sentence aligned across all 23 languages."""
    sentence_id: str
    order_index: int
    translations: Dict[str, str]

    def get_text(self, lang: str) -> str:
        return self.translations.get(lang.lower().strip(), "")

    def is_complete(self) -> bool:
        """Returns True if every one of the 23 languages has non-empty text."""
        return all(bool(self.translations.get(l, "").strip()) for l in ALL_23_LANGUAGES)


@dataclass
class AlignedParagraph:
    """A paragraph consisting of ordered aligned sentences."""
    paragraph_id: str
    order_index: int
    sentences: List[AlignedSentence] = field(default_factory=list)

    def get_paragraph_text(self, lang: str, separator: str = " ") -> str:
        texts = [s.get_text(lang) for s in self.sentences if s.get_text(lang)]
        return separator.join(texts)

    def is_complete(self) -> bool:
        return all(s.is_complete() for s in self.sentences)


@dataclass
class AlignedDocument:
    """
    A complete document aligned across all 23 languages.
    Preserves document title, domain, paragraph hierarchy, and sentence ordering.
    """
    doc_id: str
    title: Dict[str, str]
    domain: str
    summary: Dict[str, str]
    paragraphs: List[AlignedParagraph] = field(default_factory=list)
    metadata: Dict[str, Any] = field(default_factory=dict)

    def get_full_text(self, lang: str) -> str:
        """Assembles full document text for a given language."""
        title_text = self.title.get(lang, "")
        para_texts = [p.get_paragraph_text(lang) for p in self.paragraphs]
        return f"{title_text}\n\n" + "\n\n".join(para_texts)

    def get_sentence_count(self) -> int:
        return sum(len(p.sentences) for p in self.paragraphs)

    def get_word_counts(self) -> Dict[str, int]:
        counts = {}
        for l in ALL_23_LANGUAGES:
            full = self.get_full_text(l)
            counts[l] = len(full.split())
        return counts

    def is_complete(self) -> bool:
        """Checks if title and all paragraphs are present in all 23 languages."""
        has_all_titles = all(bool(self.title.get(l, "").strip()) for l in ALL_23_LANGUAGES)
        has_all_paras = all(p.is_complete() for p in self.paragraphs)
        return has_all_titles and has_all_paras

    def to_dict(self) -> Dict[str, Any]:
        return {
            "doc_id": self.doc_id,
            "title": self.title,
            "domain": self.domain,
            "summary": self.summary,
            "sentence_count": self.get_sentence_count(),
            "word_counts": self.get_word_counts(),
            "metadata": self.metadata,
            "paragraphs": [
                {
                    "paragraph_id": p.paragraph_id,
                    "order_index": p.order_index,
                    "paragraph_text": {l: p.get_paragraph_text(l) for l in ALL_23_LANGUAGES},
                    "sentences": [
                        {
                            "sentence_id": s.sentence_id,
                            "order_index": s.order_index,
                            "translations": s.translations
                        }
                        for s in p.sentences
                    ]
                }
                for p in self.paragraphs
            ]
        }


